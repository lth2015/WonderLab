CREATE TABLE entitlement_batches (
  id             CHAR(36) CHARACTER SET ascii NOT NULL,
  user_id        CHAR(36) CHARACTER SET ascii NOT NULL,
  source         VARCHAR(32)  NOT NULL,
  -- Business key of the granting event: order id, "<sub>:<invoice>", etc.
  -- With the unique key below this is what stops a replayed Stripe event from
  -- granting a second batch (PAY-05).
  source_ref     VARCHAR(191) NOT NULL,
  product_key    VARCHAR(64)  NULL,
  price_version  INT          NULL,
  granted_units  INT          NOT NULL,
  reserved_units INT          NOT NULL DEFAULT 0,
  consumed_units INT          NOT NULL DEFAULT 0,
  effective_from DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  expires_at     DATETIME(3)  NULL,
  status         VARCHAR(16)  NOT NULL DEFAULT 'active',
  created_at     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY entitlement_batches_source_uk (user_id, source, source_ref),
  KEY entitlement_batches_available_idx (user_id, status, expires_at),
  CONSTRAINT entitlement_batches_user_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT entitlement_batches_source_chk CHECK (source IN
    ('one_time_order','subscription_period','promo_trial','compensation','manual_adjustment')),
  CONSTRAINT entitlement_batches_status_chk CHECK (status IN ('active','expired','revoked')),
  -- The balance invariant. No application path can drive a batch negative or
  -- oversell it without the statement failing.
  CONSTRAINT entitlement_batches_non_negative
    CHECK (granted_units >= 0 AND reserved_units >= 0 AND consumed_units >= 0),
  CONSTRAINT entitlement_batches_not_oversold
    CHECK (reserved_units + consumed_units <= granted_units)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci
-- ;;
CREATE TABLE ledger_entries (
  id         CHAR(36) CHARACTER SET ascii NOT NULL,
  user_id    CHAR(36) CHARACTER SET ascii NOT NULL,
  batch_id   CHAR(36) CHARACTER SET ascii NULL,
  job_id     CHAR(36) CHARACTER SET ascii NULL,
  entry_type VARCHAR(16)  NOT NULL,
  units      INT          NOT NULL,
  reason     VARCHAR(255) NOT NULL,
  -- Operator id for manual adjustments; NULL for system entries (§6.2).
  actor_id   CHAR(36) CHARACTER SET ascii NULL,
  metadata   JSON         NOT NULL,
  created_at DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  -- Stands in for PostgreSQL's partial unique index. The value is NULL for
  -- entry types that may legitimately repeat, and a unique index ignores NULLs,
  -- so a job reserves at most once, consumes at most once and releases at most
  -- once. GEN-01/GEN-04/GEN-08 rely on this: a duplicated queue message or a
  -- repeated provider callback hits a duplicate-key error instead of
  -- double-charging.
  job_entry_uk CHAR(60) CHARACTER SET ascii GENERATED ALWAYS AS (
    CASE WHEN job_id IS NOT NULL
          AND entry_type IN ('reserve','consume','release','compensate')
         THEN CONCAT(job_id, ':', entry_type) END
  ) STORED,
  PRIMARY KEY (id),
  UNIQUE KEY ledger_entries_job_type_uk (job_entry_uk),
  KEY ledger_entries_user_idx (user_id, created_at DESC),
  KEY ledger_entries_batch_idx (batch_id),
  KEY ledger_entries_job_idx (job_id),
  CONSTRAINT ledger_entries_user_fk  FOREIGN KEY (user_id)  REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT ledger_entries_batch_fk FOREIGN KEY (batch_id) REFERENCES entitlement_batches (id),
  CONSTRAINT ledger_entries_actor_fk FOREIGN KEY (actor_id) REFERENCES users (id),
  CONSTRAINT ledger_entries_type_chk CHECK (entry_type IN
    ('grant','reserve','consume','release','revoke','compensate','adjust')),
  CONSTRAINT ledger_entries_units_chk CHECK (units > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci

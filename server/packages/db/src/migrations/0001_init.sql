CREATE TABLE orders (
  id                         CHAR(36) CHARACTER SET ascii NOT NULL,
  user_id                    CHAR(36) CHARACTER SET ascii NOT NULL,
  price_key                  VARCHAR(64)  NOT NULL,
  price_version              INT          NOT NULL,
  kind                       VARCHAR(16)  NOT NULL,
  amount_jpy                 INT          NOT NULL,
  currency                   VARCHAR(8)   NOT NULL DEFAULT 'jpy',
  status                     VARCHAR(24)  NOT NULL DEFAULT 'pending',
  idempotency_key            VARCHAR(128) NOT NULL,
  stripe_checkout_session_id VARCHAR(191) NULL,
  stripe_payment_intent_id   VARCHAR(191) NULL,
  stripe_customer_id         VARCHAR(191) NULL,
  entitlement_granted_at     DATETIME(3)  NULL,
  paid_at                    DATETIME(3)  NULL,
  receipt_url                VARCHAR(512) NULL,
  refunded_amount_jpy        INT          NOT NULL DEFAULT 0,
  metadata                   JSON         NOT NULL,
  created_at                 DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at                 DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY orders_idempotency_uk (user_id, idempotency_key),
  UNIQUE KEY orders_session_uk (stripe_checkout_session_id),
  UNIQUE KEY orders_intent_uk (stripe_payment_intent_id),
  KEY orders_user_idx (user_id, created_at DESC),
  KEY orders_product_idx (price_key, price_version),
  CONSTRAINT orders_user_fk    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT orders_product_fk FOREIGN KEY (price_key, price_version)
    REFERENCES product_catalog (price_key, version),
  CONSTRAINT orders_kind_chk   CHECK (kind IN ('one_time','subscription')),
  CONSTRAINT orders_status_chk CHECK (status IN
    ('pending','paid','failed','refunded','partially_refunded','canceled')),
  CONSTRAINT orders_amount_chk CHECK (amount_jpy >= 0 AND refunded_amount_jpy >= 0)

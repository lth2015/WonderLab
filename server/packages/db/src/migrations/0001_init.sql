-- Server-side, versioned operational switches (§3.2 "运营"). The API reads
-- these at request time so an operator can stop new generation without a deploy.
-- `key`/`value` are reserved words in MySQL, hence the prefixes.
CREATE TABLE runtime_settings (
  setting_key   VARCHAR(64)  NOT NULL,
  setting_value JSON         NOT NULL,
  updated_by    CHAR(36) CHARACTER SET ascii NULL,
  reason        VARCHAR(500) NULL,
  updated_at    DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (setting_key),
  CONSTRAINT runtime_settings_actor_fk FOREIGN KEY (updated_by) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci
